"""Keep immutable HUD/gun images in Archive to leave RAM for USB libraries."""
from pathlib import Path
import re,subprocess
root=Path(__file__).resolve().parents[1]
payload=bytearray()
for source in ['hud','gun']:
    text=(root/'src'/f'{source}.h').read_text()
    def replace(m):
        name,dims,body=m.groups()
        data=bytes(int(x) for x in re.findall(r'\d+',body))
        offset=len(payload);payload.extend(data)
        return f'#define {name} (*(const unsigned char (*){dims})(d84_ui_data+{offset}))'
    text=re.sub(r'static const unsigned char (\w+)((?:\[[^]]+\])+)\s*=\s*\{(.*?)\};',replace,text,flags=re.S)
    (root/'src'/f'usb_{source}.h').write_text('/* Generated by build_usb_ui.py. */\n#include "usb_audio.h"\n'+text)
(root/'build/usb-ui.raw').write_bytes(payload)
subprocess.run([str(Path.home()/'CEdev/bin/convbin'),'-j','bin','-k','8xv','-i',str(root/'build/usb-ui.raw'),'-o',str(root/'bin/D84UI.8xv'),'-n','D84UI','-r'],check=True)
print('Archived UI:',len(payload),'bytes')
