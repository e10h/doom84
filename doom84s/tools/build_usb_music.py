"""Encode the local E1M1 render as archived PCM banks for low CPU playback."""
from pathlib import Path
import wave,struct,subprocess
root=Path(__file__).resolve().parents[1]
with wave.open(str(root/'build/sounds/e1m1_mono8.wav'),'rb') as w:
    assert w.getnchannels()==1 and w.getsampwidth()==1
    rate=w.getframerate();raw=w.readframes(w.getnframes())
pcm=[]
for i in range(len(raw)*4000//rate):
    a=i*rate//4000;b=max(a+1,(i+1)*rate//4000)
    pcm.append((sum(raw[a:b])//(b-a)-128)*256)
sizes=[];counts=[]
for bank,start in enumerate(range(0,len(pcm),60000)):
    samples=pcm[start:start+60000]
    payload=b'D84P'+struct.pack('<IhBB',len(samples),0,0,0)+bytes((x//256)+128 for x in samples)
    path=root/'build'/f'music{bank}.raw';path.write_bytes(payload)
    subprocess.run([str(Path.home()/'CEdev/bin/convbin'),'-j','bin','-k','8xv','-i',str(path),'-o',str(root/'bin'/f'D84M{bank}.8xv'),'-n',f'D84M{bank}','-r'],check=True)
    sizes.append(len(payload));counts.append(len(samples))
(root/'src/usb_music_data.h').write_text('/* Generated by build_usb_music.py. */\n#define D84_MUSIC_BANKS '+str(len(sizes))+'\nstatic const unsigned int music_sizes[]={'+','.join(map(str,sizes))+'};\nstatic const unsigned int music_counts[]={'+','.join(map(str,counts))+'};\n')
print(f'{len(pcm)/4000:.2f}s E1M1, {sum(sizes)} archived PCM bytes, {len(sizes)} banks')
(root/'build/music-decoded.pcm').write_bytes(b''.join(struct.pack('<h',x) for x in pcm))
