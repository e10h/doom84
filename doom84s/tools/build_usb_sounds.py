"""Resample local Doom SFX WAVs into a compact 4 kHz calculator table."""
from pathlib import Path
import wave
root=Path(__file__).resolve().parents[1]
names=['pistol','pldeth','plpain','podth','popain','doropn','swtchn','itemup','barexp']
lines=['/* Generated by tools/build_usb_sounds.py. */','#include <stdint.h>']
lengths=[]
payload=bytearray()
offsets=[]
for i,name in enumerate(names):
    with wave.open(str(root/'build/sounds'/('sfx_'+name+'.wav')),'rb') as w:
        assert w.getsampwidth()==1 and w.getnchannels()==1
        rate=w.getframerate(); raw=w.readframes(w.getnframes())
    count=len(raw)*4000//rate
    data=[]
    for j in range(count):
        start=j*rate//4000
        end=min(len(raw),max(start+1,(j+1)*rate//4000))
        data.append(sum(raw[start:end])//(end-start))
    lengths.append(count)
    offsets.append(len(payload));payload.extend(data)
lines.append('static const unsigned int d84_offsets[]={'+','.join(map(str,offsets))+'};')
lines.append('static const unsigned int d84_lengths[]={'+','.join(map(str,lengths))+'};')
(root/'src/usb_samples.h').write_text('\n'.join(lines)+'\n')
print('4 kHz SFX:',sum(lengths),'bytes')

(root/'build/usb-sfx.raw').write_bytes(payload)
