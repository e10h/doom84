#!/usr/bin/env python3
"""Share transformed/projected E1M1 vertices and BSP bounding-box corners."""
import re,struct
from pathlib import Path
def build_geometry(root):
    root=Path(root)
    h=(root/'src/generated.h').read_text();data=(root/'build/D84MAP.bin').read_bytes()
    def value(name):return int(re.search(r'#define '+name+r' (\d+)',h)[1])
    points=[struct.unpack_from('<hh',data,value('OFF_VERTICES')+4*i) for i in range(value('NUM_VERTICES'))]
    lookup={point:i for i,point in enumerate(points)};indices=[]
    for i in range(value('NUM_NODES')):
     for side in range(2):
      top,bottom,left,right=struct.unpack_from('<hhhh',data,value('OFF_NODES')+28*i+8+side*8)
      corners=[]
      for point in [(left,top),(left,bottom),(right,top),(right,bottom)]:
       if point not in lookup:lookup[point]=len(points);points.append(point)
       corners.append(lookup[point])
      indices.append(corners)
    extra=points[value('NUM_VERTICES'):]
    out=['/* Generated by tools/build_geometry.py. */',f'#define NUM_RENDER_POINTS {len(points)}',f'static const Vertex extra_points[{len(extra)}]={{'+','.join('{%d,%d}'%p for p in extra)+'};',f'static const uint16_t box_points[{len(indices)}][4]={{'+','.join('{'+','.join(map(str,row))+'}' for row in indices)+'};']
    out.append('static const uint16_t node_offsets[NUM_NODES]={'+','.join(str(i*28) for i in range(value('NUM_NODES')))+'};')
    out.append('static const uint16_t sector_offsets[NUM_SECTORS]={'+','.join(str(i*10) for i in range(value('NUM_SECTORS')))+'};')
    (root/'src/geometry_abi.h').write_text(f'/* Generated geometry counts for assembly. */\n#define D84_VERTEX_COUNT {value("NUM_VERTICES")}\n#define D84_NODE_COUNT {value("NUM_NODES")}\n')
    (root/'src/geometry.h').write_text('\n'.join(out)+'\n')
    def numbers(name):
        return list(map(int,re.search(name+r'\[[^;]*?= \{([^}]+)',h)[1].split(',')))
    banks=numbers('tile_bank');offsets=numbers('tile_offset')
    frames=[]
    for tile in (value('GUN_TILE'),value('FIRE_TILE')):
        image=(root/f'build/D84T{banks[tile]}.bin').read_bytes()[offsets[tile]:]
        frames.append([image[(y*64//28)*64+x*64//25] for y in range(28) for x in range(25)])
    (root/'src/gun.h').write_text('/* Generated pre-scaled pistol frames. */\nstatic const unsigned char gun_frames[2][700]={'+','.join('{'+','.join(map(str,frame))+'}' for frame in frames)+'};\n')

if __name__=='__main__':
    build_geometry(Path(__file__).resolve().parents[1])
